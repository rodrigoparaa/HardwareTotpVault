void font_draw_char(int x, int y, uint8_t ch, int scale, uint32_t color) {
    if (scale <= 0) scale = 1;
    if (ch >= 128) ch = '?';

    const uint8_t *glyph = FONT_8X8[ch];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                if (scale == 1) {
                    gfx_draw_rect_fill(x + col, y + row, 1, 1, color);
                } else {
                    gfx_draw_rect_fill(x + (col * scale), y + (row * scale), scale, scale, color);
                }
            }
        }
    }
}

/* Streaming UTF-8 Decoder that maps accented vowels/symbols to safe glyphs */
static uint8_t decode_utf8(const char **pstr) {
    const uint8_t *p = (const uint8_t *)*pstr;
    if (*p == 0) return 0;

    if (*p < 0x80) {
        (*pstr)++;
        return *p;
    }

    /* 2-byte sequences: Spanish vowels and accents */
    if (*p == 0xC3 && *(p + 1) != 0) {
        uint8_t next = *(p + 1);
        *pstr += 2;
        switch (next) {
            case 0xA1: return 'a'; /* á */
            case 0xA9: return 'e'; /* é */
            case 0xAD: return 'i'; /* í */
            case 0xB3: return 'o'; /* ó */
            case 0xBA: return 'u'; /* ú */
            case 0xB1: return 'n'; /* ñ */
            case 0x81: return 'A'; /* Á */
            case 0x89: return 'E'; /* É */
            case 0x8D: return 'I'; /* Í */
            case 0x93: return 'O'; /* Ó */
            case 0x9A: return 'U'; /* Ú */
            case 0x91: return 'N'; /* Ñ */
            default:   return '?';
        }
    }

    if (*p == 0xC2 && *(p + 1) != 0) {
        uint8_t next = *(p + 1);
        *pstr += 2;
        if (next == 0xBF) return '?'; /* ¿ */
        if (next == 0xA1) return '!'; /* ¡ */
        return ' ';
    }

    /* 3-byte sequences: Bullet • (\xE2\x80\xA2) */
    if (*p == 0xE2 && *(p + 1) == 0x80 && *(p + 2) == 0xA2) {
        *pstr += 3;
        return 1; /* Custom bullet glyph */
    }

    /* Skip unknown multi-byte */
    if ((*p & 0xE0) == 0xC0) { *pstr += 2; return '?'; }
    if ((*p & 0xF0) == 0xE0) { *pstr += 3; return '?'; }
    if ((*p & 0xF8) == 0xF0) { *pstr += 4; return '?'; }

    (*pstr)++;
    return '?';
}

int font_string_width(const char *str, int scale) {
    if (!str || scale <= 0) return 0;
    int count = 0;
    const char *p = str;
    while (*p) {
        decode_utf8(&p);
        count++;
    }
    return count * (8 * scale);
}

void font_draw_string(int x, int y, const char *str, int scale, uint32_t color) {
    if (!str) return;
    if (scale <= 0) scale = 1;

    int cur_x = x;
    const char *p = str;
    while (*p) {
        uint8_t ch = decode_utf8(&p);
        font_draw_char(cur_x, y, ch, scale, color);
        cur_x += (8 * scale);
    }
}

void font_draw_string_centered(int y, const char *str, int scale, uint32_t color) {
    if (!str) return;
    int w = font_string_width(str, scale);
    int x = (SCREEN_WIDTH - w) / 2;
    font_draw_string(x, y, str, scale, color);
}

void font_draw_string_truncated(int x, int y, const char *str, int max_w, int scale, uint32_t color) {
    if (!str || max_w <= 0) return;
    if (scale <= 0) scale = 1;

    int char_w = 8 * scale;
    int cur_x = x;
    const char *p = str;

    while (*p) {
        if (cur_x + char_w > x + max_w) {
            /* Append ellipsis if room */
            if (cur_x + (char_w * 3) <= x + max_w + (char_w * 2)) {
                font_draw_char(cur_x, y, '.', scale, color);
                font_draw_char(cur_x + char_w, y, '.', scale, color);
                font_draw_char(cur_x + (char_w * 2), y, '.', scale, color);
            }
            break;
        }
        uint8_t ch = decode_utf8(&p);
        font_draw_char(cur_x, y, ch, scale, color);
        cur_x += char_w;
    }
}
